#!/usr/bin/env python3
"""Generate scr_trackdata.h: the flash tables the on-demand track module needs.
Source: the remake's own converted tables (orig_tracks.json, dumped from its build) and
the 8 raw track files. usage: gen_trackdata.py orig_tracks.json Tracks/"""
import sys, json, os
d = json.load(open(sys.argv[1])); tdir = sys.argv[2]
names = ['LittleRamp','SteppingStones','HumpBack','BigRamp','SkiJump','DrawBridge','HighJump','RollerCoaster']
o = ['/* generated by gen_trackdata.py - do not edit */', '#pragma once', '#include "scr_platform.h"']
import re
vals, offs = [], []
for prof in d['piece_y']:
    offs.append(len(vals)); vals += prof
assert all(-32768 <= v <= 32767 for v in vals)
T = d['templates']; xz, xoff = [], []
for t in T:
    xoff.append(len(xz) // 2)
    for x, z in t['xz']: xz += [x, z]
assert all(-32768 <= v <= 32767 for v in xz)
for key, name in [('ns','ns'),('left','left'),('type','type'),('lr','lr'),('steer','steer')]:
    o.append(f'static const uint8_t scr_tmpl_{name}[11] PROGMEM = {{{",".join(str(t[key]) for t in T)}}};')
o.append(f'static const uint8_t scr_tmpl_xzoff[11] PROGMEM = {{{",".join(map(str, xoff))}}};')
# sin / atan tables: the exact values scr_math.cpp has used so far
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'scr_math_tables.txt')).read()
def arr(name):
    m = re.search(name + r'\[257\][^=]*=\s*\{([^}]*)\}', src)
    return [int(v) for v in m.group(1).split(',')]
sin_t, atan_t = arr('sin_q15'), arr('atan_q2')

# ---- SCRTRK.BIN: the 8 tracks for the SD card, one 2 KB slot each, laid out for the
# SPI RAM accessor: header, 16-byte piece records, Track_Map
SLOT = 2048
blob = bytearray(SLOT * 8)
for ti, n in enumerate(names):
    b = open(os.path.join(tdir, n + '.bin'), 'rb').read(); assert len(b) == 804
    tr = d['tracks'][ti]; np_ = b[0]; assert np_ == tr['n']
    s = blob[ti * SLOT:(ti + 1) * SLOT] = bytearray(SLOT)
    base = ti * SLOT
    blob[base + 0] = np_; blob[base + 1] = b[1]; blob[base + 2] = b[802]; blob[base + 3] = b[803]
    blob[base + 4:base + 6] = tr['segs'].to_bytes(2, 'little')
    for p in range(np_):
        r = base + 16 + p * 16
        f = tr['pieces'][p]
        steep = sum(1 << i for i, c in enumerate(f['rc']) if c == 26)       # SCR_BASE_COLOUR + 0
        blob[r + 0] = b[2 + p]; blob[r + 1] = b[102 + p]; blob[r + 2] = b[202 + p]; blob[r + 3] = b[302 + p]
        blob[r + 4:r + 6] = b[402 + 2 * p:404 + 2 * p]                   # left shift, big-endian
        blob[r + 6:r + 8] = b[602 + 2 * p:604 + 2 * p]                   # right shift, big-endian
        blob[r + 8:r + 10] = f['f'][10].to_bytes(2, 'little')            # firstSegment
        blob[r + 10:r + 12] = steep.to_bytes(2, 'little')                # steep-segment mask
        # renderer: bounding sphere (display units: x, z within the cube, y / 4), in units of 64
        cs = [(c[0], c[1] // 4 if c[1] >= 0 else -((-c[1]) // 4), c[2]) for c in f['c']]
        mn = [min(v[i] for v in cs) for i in range(3)]; mx = [max(v[i] for v in cs) for i in range(3)]
        cen = [(mn[i] + mx[i]) / 2 for i in range(3)]
        rad = max(((v[0]-cen[0])**2 + (v[1]-cen[1])**2 + (v[2]-cen[2])**2) ** 0.5 for v in cs)
        cx8, cy8, cz8 = round(cen[0] / 64), round(cen[1] / 64), round(cen[2] / 64)
        r8 = int(-(-(rad + 64 * 1.5) // 64))                             # rounded up, plus centre rounding
        if n == 'DrawBridge' and 50 <= p <= 56: r8 += 40                 # drawbridge pieces move (up ~2400)
        assert -128 <= cx8 <= 127 and -128 <= cz8 <= 127 and 0 <= cy8 <= 255 and r8 <= 255
        blob[r + 12] = cx8 & 0xFF; blob[r + 13] = cy8; blob[r + 14] = cz8 & 0xFF; blob[r + 15] = r8
    m = [0xFF] * 256
    for p in range(np_):
        c = b[2 + p]; m[(c & 0x0f) * 16 + ((c >> 4) & 0x0f)] = p        # Track_Map[x][z], last wins
    blob[base + 1664:base + 1920] = bytes(m)             # after 16 + 100 * 16 bytes of records
# ---- table area after the tracks (read through the SPI RAM)
TAB = len(blob)
def w16(lst, signed=True):
    return b''.join(int(v).to_bytes(2, 'little', signed=signed) for v in lst)
parts = [('PIECE_Y', w16(vals)), ('PIECE_Y_OFF', w16(offs, False)), ('TMPL_XZ', w16(xz)),
         ('SIN', w16(sin_t, False)), ('ATAN', w16(atan_t, False))]
for name, data in parts:
    o.append(f'#define SCR_T_{name} 0x{len(blob):05X}UL     /* {len(data)} bytes */')
    blob += data
while len(blob) % 512: blob.append(0)
o.append(f'#define SCR_DATA_SIZE {len(blob)}')
o.append(f'#define SCR_DATA_SUM 0x{sum(blob) & 0xFFFF:04X}     /* the 16-bit sum of its bytes: checked when loaded from the .uze */')
open('SCRTRK.BIN', 'wb').write(blob)
o.append(f'#define SCR_TRACK_SLOT {SLOT}')
open('scr_trackdata.h', 'w').write('\n'.join(o) + '\n')
print(f'height values {len(vals)}, template points {len(xz)//2}; SCRTRK.BIN {len(blob)} bytes (tables {len(blob) - TAB})')
